"""Расчёт показателей внимания по методике Шульте."""
from __future__ import annotations

from attention_system.business.errors import ОшибкаДанных
from attention_system.markup import стереотип


@стереотип("служба")
class РасчётПоказателей:
    """Формулы методики: ЭР = (T1+...+T5)/5, ВР = T1/ЭР, ПУ = T4/ЭР."""

    ЧИСЛО_ТАБЛИЦ = 5

    @staticmethod
    def рассчитать(времена: list[float]) -> tuple[float, float, float]:
        if len(времена) != РасчётПоказателей.ЧИСЛО_ТАБЛИЦ:
            raise ОшибкаДанных("Для расчёта нужно время прохождения ровно пяти таблиц")
        if any(t is None or t <= 0 for t in времена):
            raise ОшибкаДанных("Время прохождения таблицы должно быть положительным")
        эр = sum(времена) / РасчётПоказателей.ЧИСЛО_ТАБЛИЦ
        вр = времена[0] / эр
        пу = времена[3] / эр
        return эр, вр, пу
