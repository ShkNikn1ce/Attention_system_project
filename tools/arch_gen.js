// Архитектурные диаграммы: уровни, подсистемы и интерфейсы, размещение, состояния.
module.exports = async function (КЛ, бокс, сохранить, T, LINE, строкиКласса) {
  const FONT = "Arial";
  const рамка = (x, y, w, h, o = {}) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="white" stroke="black" stroke-width="${o.sw || 1.8}" ${o.dash ? 'stroke-dasharray="7,5"' : ""} rx="${o.rx || 0}"/>`;
  const перенос = (текст, макс) => { const сл = текст.split(" "), стр = []; let т = ""; for (const с of сл) { if ((т + " " + с).trim().length > макс) { стр.push(т); т = с; } else т = (т + " " + с).trim(); } if (т) стр.push(т); return стр; };

  // ---------- 1. архитектурные уровни ----------
  {
    const W = 1160; let y = 30, s = "";
    const уровень = (название, строки, h, подсистемы) => {
      s += рамка(40, y, W - 80, h);
      s += T("«layer»", 60, y + 20, { a: "start", it: true, fs: 12 }) + T(название, 60, y + 40, { a: "start", b: true, fs: 15 });
      let ty = y + 66;
      строки.forEach(стр => { перенос(стр, 120).forEach(л => { s += T(л, 70, ty, { a: "start", fs: 13 }); ty += 19; }); });
      if (подсистемы) {
        const n = подсистемы.length, ширина = (W - 80 - 40 - (n - 1) * 20) / n;
        подсистемы.forEach((п, i) => {
          const x = 60 + i * (ширина + 20), yy = y + 56;
          s += рамка(x, yy, ширина, h - 72, { sw: 1.4 }) + T("«subsystem»", x + ширина / 2, yy + 18, { it: true, fs: 11.5 }) + T(п[0], x + ширина / 2, yy + 36, { b: true, fs: 13 });
          let py = yy + 58; п[1].forEach(л => { s += T(л, x + 10, py, { a: "start", fs: 12 }); py += 17; });
        });
      }
      y += h + 38;
    };
    const линияМеж = [];
    const шаги = [];
    уровень("Прикладной уровень (Application Subsystems)", ["Граничные классы: ФормаВхода, ФормаТестирования, ФормаМоихРезультатов, ФормаНазначенияТестирования, ФормаРезультатовПилота, ФормаЗаключения, ФормаДинамики, ФормаДанныхПилотов, ФормаНормДопуска, ФормаСводногоОтчёта, Экран", "Управляющие классы: десять контроллеров (по одному на вариант использования)", "Активный класс «process»: СерверПриложения"], 130);
    шаги.push(y - 38);
    уровень("Бизнес-уровень (Business-specific)", ["Классы-сущности: Пользователь, Пилот, АвиационныйПсихолог, Администратор, СессияТестирования, ТаблицаШульте, РезультатТестирования, НормаДопуска, ЗаключениеОДопуске, СводныйОтчёт", "Бизнес-службы: РасчётПоказателей, ОценкаДопуска, АнализДинамики, СервисОтчётов"], 110);
    шаги.push(y - 38);
    уровень("Промежуточный уровень (Middleware)", [], 195, [
      ["Хранилище данных", ["IХранилище", "ХранилищеSQLite", "(посредник подсистемы)"]],
      ["Безопасность", ["ХэшПароля", "КонтрольДоступа", "Сеанс"]],
      ["Внешние интерфейсы", ["IИнтерфейсУведомлений", "IИнтерфейсСлужбы-", "Безопасности"]],
      ["Измерение времени", ["Секундомер", "СекундомерСистемный"]]]);
    шаги.push(y - 38);
    уровень("Системный уровень (System software)", ["Python 3.12 и стандартная библиотека (sqlite3, threading, hashlib), операционная система"], 80);
    шаги.forEach(yy => { s += LINE(W / 2, yy - 0, W / 2, yy + 38, true) + LINE(W / 2 - 200, yy, W / 2 - 200, yy + 38, true) + LINE(W / 2 + 200, yy, W / 2 + 200, yy + 38, true); });
    await сохранить("arch_layers", s, W, y);
  }

  // ---------- 2. подсистемы и интерфейсы (реализация интерфейсов) ----------
  {
    const интХр = КЛ["IХранилище"].операции.map(о => о.имя);
    const A = бокс("IХранилище", 40, 40), B = бокс("ХранилищеSQLite", 40 + A.w + 160, 40, { скрыть: интХр });
    let y = Math.max(A.bottom, B.bottom) + 70;
    const пары = [["IИнтерфейсУведомлений", "УведомленияВПамяти"], ["IИнтерфейсСлужбыБезопасности", "СлужбаБезопасностиВПамяти"]];
    const все = [A, B]; let лин = "";
    const реализ = (имп, инт) => {
      const yy = Math.max(Math.min(инт.bottom, имп.bottom) - 14, Math.max(инт.y, имп.y) + 40);
      if (имп.x > инт.right) { const x = инт.right; лин += LINE(имп.x, yy, x + 16, yy, true) + `<polygon points="${x},${yy} ${x + 16},${yy - 8} ${x + 16},${yy + 8}" fill="white" stroke="black" stroke-width="1.6"/>`; }
      else { const x = инт.x; лин += LINE(имп.right, yy, x - 16, yy, true) + `<polygon points="${x},${yy} ${x - 16},${yy - 8} ${x - 16},${yy + 8}" fill="white" stroke="black" stroke-width="1.6"/>`; }
    };
    реализ(B, A);
    for (const [и, р] of пары) { const bi = бокс(и, 40, y), br = бокс(р, 40 + bi.w + 160, y); все.push(bi, br); реализ(br, bi); y = Math.max(bi.bottom, br.bottom) + 70; }
    const секунд = бокс("Секундомер", 40 + 290 + 160, y), сс = бокс("СекундомерСистемный", 40, y), сп = бокс("СекундомерПоСценарию", секунд.right + 160, y);
    все.push(секунд, сс, сп); реализ(сс, секунд);
    { const yy = секунд.cy + 6; лин += LINE(сп.x, yy, секунд.right + 16, yy, true) + `<polygon points="${секунд.right},${yy} ${секунд.right + 16},${yy - 8} ${секунд.right + 16},${yy + 8}" fill="white" stroke="black" stroke-width="1.6"/>`; }
    // сс слева от интерфейса: линия идёт вправо
    лин = лин.replace(/$/, "");
    const mx = Math.max(...все.map(b => b.right)) + 40, my = Math.max(...все.map(b => b.bottom)) + 30;
    await сохранить("arch_interfaces", лин + все.map(b => b.svg).join(""), mx, my);
  }

  // ---------- 3. диаграмма размещения ----------
  {
    const W = 1200; let s = "";
    const узел = (x, y, w, h, название, строки) => {
      s += рамка(x, y, w, h) + `<polyline points="${x},${y} ${x + 14},${y - 12} ${x + w + 14},${y - 12} ${x + w + 14},${y + h - 12} ${x + w},${y + h}" fill="none" stroke="black" stroke-width="1.4"/><line x1="${x + w}" y1="${y}" x2="${x + w + 14}" y2="${y - 12}" stroke="black" stroke-width="1.4"/>`;
      s += T("«узел»", x + w / 2, y + 22, { it: true, fs: 12 }) + T(название, x + w / 2, y + 42, { b: true, fs: 14 });
      let ty = y + 70; строки.forEach(л => { s += T(л, x + 14, ty, { a: "start", fs: 12.5 }); ty += 19; });
    };
    узел(40, 60, 300, 230, "Рабочее место пользователя", ["ПК или планшет (пилот, психолог,", "администратор)", "Артефакты: граничные классы", "(формы), Экран, Секундомер"]);
    узел(500, 60, 340, 230, "Сервер приложения", ["Процесс «СерверПриложения»", "(пул из 50 потоков)", "Управляющие классы, сущности,", "службы, ХранилищеSQLite"]);
    узел(1000, 60, 160, 110, "Файл БД", ["SQLite", "«database»"]);
    узел(1000, 220, 160, 110, "Служба безопас-", ["ности полётов", "(внешняя система)"]);
    s += LINE(354, 175, 500, 175) + T("локальная сеть", 427, 160, { fs: 12.5, it: true });
    s += LINE(854, 115, 1000, 115) + T("SQL", 927, 100, { fs: 12.5, it: true });
    s += LINE(854, 255, 1000, 255, true) + T("интерфейс", 927, 240, { fs: 12.5, it: true });
    await сохранить("arch_deploy", s, W, 360);
  }

  // ---------- 4. состояния СессияТестирования ----------
  {
    const W = 1000; let s = "";
    const состояние = (cx, cy, текст) => { s += `<rect x="${cx - 90}" y="${cy - 30}" width="180" height="60" rx="26" fill="white" stroke="black" stroke-width="1.8"/>` + T(текст, cx, cy + 5, { b: true, fs: 14 }); };
    const стрелка = (x1, y1, x2, y2) => { const a = Math.atan2(y2 - y1, x2 - x1); s += LINE(x1, y1, x2 - 10 * Math.cos(a), y2 - 10 * Math.sin(a)) + `<polygon points="${x2},${y2} ${x2 - 12 * Math.cos(a - 0.4)},${y2 - 12 * Math.sin(a - 0.4)} ${x2 - 12 * Math.cos(a + 0.4)},${y2 - 12 * Math.sin(a + 0.4)}" fill="black"/>`; };
    s += `<circle cx="500" cy="40" r="11" fill="black"/>`; стрелка(500, 51, 500, 110);
    состояние(500, 140, "Назначена"); состояние(850, 140, "Завершена"); состояние(150, 140, "Отменена");
    стрелка(590, 140, 760, 140); s += T("завершить()", 675, 124, { fs: 13, it: true }) + T("[сохранён результат]", 675, 163, { fs: 12, it: true });
    стрелка(410, 140, 240, 140); s += T("отменить()", 325, 124, { fs: 13, it: true });
    стрелка(850, 170, 850, 235); стрелка(150, 170, 150, 235);
    for (const cx of [850, 150]) s += `<circle cx="${cx}" cy="250" r="14" fill="white" stroke="black" stroke-width="1.8"/><circle cx="${cx}" cy="250" r="8" fill="black"/>`;
    await сохранить("arch_state", s, W, 290);
  }
  console.log("архитектурные диаграммы готовы");
};
