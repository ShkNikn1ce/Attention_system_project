"""Исключения предметной области."""


class ОшибкаПредметнойОбласти(Exception):
    """Базовое исключение системы."""


class ОшибкаДанных(ОшибкаПредметнойОбласти):
    """Некорректные или конфликтующие данные."""


class ОшибкаСостояния(ОшибкаПредметнойОбласти):
    """Операция недопустима в текущем состоянии объекта."""


class ОшибкаДоступа(ОшибкаПредметнойОбласти):
    """У пользователя нет прав на операцию."""


class НетДанных(ОшибкаПредметнойОбласти):
    """Запрошенные данные отсутствуют."""


class ОшибкаВхода(ОшибкаПредметнойОбласти):
    """Неверный логин или пароль."""


class ОшибкаБлокировки(ОшибкаВхода):
    """Превышено число попыток входа."""
